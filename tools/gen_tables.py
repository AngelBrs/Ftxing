import re, json
src = open('/tmp/constants.c').read()

def grab_block(name):
    i = src.index(name)
    j = src.index('{', i); j = src.index('{', j+1)
    k = src.index('};', i)
    return src[i:k]

# 174,91 generator
blk = grab_block('kFTX_LDPC_generator')
rows = re.findall(r'\{([^{}]*)\}', blk)
gen91 = []
for r in rows:
    bs = [int(x,16) for x in re.findall(r'0x([0-9a-fA-F]{2})', r)]
    assert len(bs)==12
    bits = ''.join(f'{b:08b}' for b in bs)[:91]
    gen91.append(bits)
assert len(gen91)==83, len(gen91)

# 174,87 generator (JS8 / FT8 v1)
f = open('/tmp/ldpc87.f90').read()
hexrows = re.findall(r'"([0-9a-f]{22})"', f)
assert len(hexrows)==87, len(hexrows)
gen87 = []
for h in hexrows:
    bits = ''.join(f'{int(c,16):04b}' for c in h)[:87]
    gen87.append(bits)

def hexpack(bits, nbytes):
    b = bits + '0'*(nbytes*8-len(bits))
    return ''.join(f'{int(b[i:i+8],2):02x}' for i in range(0,nbytes*8,8))

out = []
out.append('// AUTO-GENERATED by tools/gen_tables.py — do not edit by hand.')
out.append('// Sources:')
out.append('//   LDPC(174,91) parity generator  : kgoba/ft8_lib ft8/constants.c (from WSJT-X)')
out.append('//   LDPC(174,87) parity generator  : js8call/lib/ft8/ldpc_174_87_params.f90 (from WSJT-X v1 / JS8)')
out.append('//   Costas / Gray / FT4 XOR tables : ft8_lib ft8/constants.c, js8call lib/js8/genjs8.f90')
out.append('')
out.append('/** Parity-generator rows for the (174,91) code, hex-packed MSB-first, 91 bits used per row. */')
out.append('export const LDPC_174_91_GEN_HEX: string[] = ' + json.dumps([hexpack(b,12) for b in gen91], indent=0).replace('\n','') + ';')
out.append('')
out.append('/** Parity-generator rows for the (174,87) code (JS8), hex-packed MSB-first, 87 bits used per row. */')
out.append('export const LDPC_174_87_GEN_HEX: string[] = ' + json.dumps([hexpack(b,11) for b in gen87], indent=0).replace('\n','') + ';')
out.append('')
out.append('export const FT8_COSTAS: number[] = [3, 1, 4, 0, 6, 5, 2];')
out.append('export const FT4_COSTAS: number[][] = [[0,1,3,2],[1,0,2,3],[2,3,1,0],[3,2,0,1]];')
out.append('export const FT8_GRAY: number[] = [0, 1, 3, 2, 5, 6, 4, 7];')
out.append('export const FT4_GRAY: number[] = [0, 1, 3, 2];')
out.append('export const FT4_XOR: number[] = [0x4a,0x5e,0x89,0xb4,0xb0,0x8a,0x79,0x55,0xbe,0x28];')
out.append('/** JS8 Costas arrays (NCOSTAS=1, the JS8Call default): identical for all three groups. */')
out.append('export const JS8_COSTAS: number[] = [4, 2, 5, 6, 1, 3, 0];')
open('/home/user/radiolink/src/protocols/tables.ts','w').write('\n'.join(out) + '\n')
print('ok', len(gen91), len(gen87))
